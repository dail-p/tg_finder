from __future__ import annotations

from aiogram import Router
from aiogram.filters import Command
from aiogram.types import Message

base_router = Router(name="basic")

START_TEXT = (
    "<b>Поиск по вашим Telegram-каналам</b>\n\n"
    "Собери каналы в персональные папки, дождись индексации и задавай вопросы по "
    "содержимому постов. Ответ будет содержать ссылки на источники.\n\n"
    "/folders — создать папки и управлять каналами\n"
    "/search <i>&lt;вопрос&gt;</i> — искать по всем вашим папкам\n"
    "/help — подробная инструкция"
)

HELP_TEXT = (
    "<b>Как пользоваться ботом</b>\n\n"
    "<b>1. Создайте папку</b>\n"
    "Откройте /folders, нажмите «Новая папка» и отправьте её название. Папки "
    "видны только вам и позволяют разделить каналы по темам.\n\n"
    "<b>2. Добавьте канал</b>\n"
    "Откройте папку, нажмите «Канал» и отправьте <code>@username</code>, ссылку вида "
    "<code>t.me/channel</code> или перешлите пост из канала. После добавления бот "
    "сразу индексирует доступную историю. Для закрытого канала Telegram-сессия бота "
    "должна иметь к нему доступ.\n\n"
    "<b>3. Обновляйте индекс</b>\n"
    "Нажмите на канал в папке, затем «Обновить посты». Бот загрузит только новые "
    "посты. Автоматическое обновление также выполняется по расписанию.\n\n"
    "<b>4. Выполняйте поиск</b>\n"
    "Кнопка «Поиск по папке» ищет только в выбранной папке. Команда "
    "<code>/search ваш вопрос</code> ищет по каналам из всех ваших папок. Бот "
    "составит ответ и приложит ссылки на посты-источники.\n\n"
    "<b>5. Управляйте структурой</b>\n"
    "В папке можно изменить её название или удалить целиком. В карточке канала "
    "можно удалить его из папки. Если канал был последним, пустая папка тоже "
    "удалится. Канал в папках других пользователей и его посты при этом не "
    "затрагиваются.\n\n"
    "<b>Команды</b>\n"
    "/folders — папки и каналы\n"
    "/search <i>&lt;вопрос&gt;</i> — поиск по всем вашим каналам\n"
    "/cancel — отменить ввод названия, канала или вопроса\n"
    "/help — показать эту инструкцию\n\n"
    "<i>Значок ожидания рядом с каналом означает, что в индексе ещё нет постов.</i>"
)


@base_router.message(Command("start"))
async def cmd_start(message: Message) -> None:
    await message.answer(START_TEXT)


@base_router.message(Command("help"))
async def cmd_help(message: Message) -> None:
    await message.answer(HELP_TEXT)


@base_router.message()
async def fallback(message: Message) -> None:
    await message.answer(
        "Используйте /folders для управления каналами или "
        "/search <i>&lt;вопрос&gt;</i> для поиска. Подробности: /help"
    )
